"""Authenticated Garmin Connect client.

Logs in with your own Garmin email and password via the `garminconnect`
package and reads your own data. Garmin publishes no consumer API, so this
goes through the same endpoints the Garmin Connect app uses. It is not a
supported public API and Garmin can change it without notice.

This class is the only place in the project that logs in to Garmin — the
workout writer imports it too (`garmin_workout_writer._build_client`), so the
whole Garmin path, read and write, comes through here.

WHAT THE LIBRARY DOES ON THE WAY IN. Worth knowing before relying on this,
because it is not what the docstring here used to claim. `garminconnect`
0.3.2 does not simply POST your credentials. `Garmin.login()` runs a chain of
five strategies in order (iOS app endpoint, iOS app over plain requests, an
SSO embed widget, the web portal, the web portal over plain requests), and:

  - three of them use `curl_cffi` with `impersonate=`, which presents the TLS
    fingerprint of Safari, Safari iOS, Chrome or Edge rather than Python's
    (client.py:301, 412, 576), and two of those rotate through that list of
    profiles when one is refused, because — the library's comment — different
    fingerprints land in different Cloudflare rate-limit buckets;
  - the portal strategy sends a randomised browser User-Agent and matching
    sec-ch-ua headers, generated by `ua-generator` (client.py:94, 609);
  - two of them sleep a random 3-8 or 10-20 seconds before posting, which the
    library's own constants call an "anti-WAF delay" and its own comment
    explains as Cloudflare flagging rapid GET-POST sequences as bot-like
    (client.py:450, 634).

That is browser impersonation, and it is how essentially all third-party
Garmin tooling authenticates, because the alternative is no access at all.
This project writes none of it and adds none of it; it also does not avoid
it, because it is inside the dependency. The account is yours, the
credentials are yours, and nothing but your own login is sent to Garmin's own
login endpoint — but the path runs through that library, and whether to
depend on it is your call. See "How this reaches Garmin" in the README.

A side effect worth expecting: if the first strategies are refused, a single
login can sit there for the better part of a minute before it succeeds or
gives up. That is the sleeps above, not a hang.

TWO-FACTOR AUTHENTICATION IS NOT SUPPORTED. `Garmin(...)` is constructed
below without a `prompt_mfa` callback, so an account with 2FA turned on
fails login with "MFA Required but no prompt_mfa mechanism supplied". This
has never been run against a real 2FA account.
"""

import os

from dotenv import load_dotenv
from garminconnect import Garmin

load_dotenv()


class GarminClient:
    def __init__(self, email=None, password=None):
        email = email or os.environ["GARMIN_EMAIL"]
        password = password or os.environ["GARMIN_PASSWORD"]
        self._api = Garmin(email, password)
        self._api.login()

    def recent_activities(self, limit=10):
        return self._api.get_activities(0, limit)

    def latest_activity(self):
        activities = self.recent_activities(limit=1)
        return activities[0] if activities else None

    def activity_details(self, activity_id):
        return self._api.get_activity_details(activity_id)

    def daily_stats(self, date_str):
        """date_str format: YYYY-MM-DD"""
        return self._api.get_stats(date_str)

    def training_status(self, date_str):
        return self._api.get_training_status(date_str)


if __name__ == "__main__":
    client = GarminClient()
    latest = client.latest_activity()
    if latest:
        print(f"Latest activity: {latest.get('activityName')} "
              f"({latest.get('startTimeLocal')})")
    else:
        print("No recent activities found.")
